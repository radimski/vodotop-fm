/* Self-host the webfonts.
   Downloads WOFF2 files from Google Fonts into ../fonts/ and writes ../fonts.css.
   Run once (or whenever the weights below change):  node build/fonts.js
   After this the site makes ZERO external requests. */
const fs = require('fs');
const path = require('path');

const SITE = path.resolve(__dirname, '..', 'site');
const OUT_DIR = path.join(SITE, 'fonts');
const CSS_OUT = path.join(SITE, 'fonts.css');

// Weight RANGES (`400..700`) make Google serve one variable file per subset
// instead of one static file per weight — 4 files instead of 14, and every
// weight in between is available for free.
const CSS_URL =
  'https://fonts.googleapis.com/css2' +
  '?family=Source+Sans+3:wght@400..700' +
  '&display=swap';

// Chrome UA is what makes Google serve woff2 instead of ttf
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36';

// latin-ext carries the Slovak/Polish diacritics (ľ ť ň š č ž ó ą ę ł ż ź ć ń ś)
const KEEP_SUBSETS = ['latin', 'latin-ext'];

(async () => {
  fs.mkdirSync(OUT_DIR, { recursive: true });

  const css = await (await fetch(CSS_URL, { headers: { 'User-Agent': UA } })).text();

  // Google's CSS is a run of `/* subset */ @font-face { ... }` blocks
  const parts = css.split('/*').slice(1);
  let out = '/* Self-hosted webfonts — generated by build/fonts.js, do not edit by hand */\n';
  let count = 0;
  let bytes = 0;

  for (const part of parts) {
    const subset = part.slice(0, part.indexOf('*/')).trim();
    if (!KEEP_SUBSETS.includes(subset)) continue;

    const block = part.slice(part.indexOf('*/') + 2);
    const fam = (block.match(/font-family:\s*'([^']+)'/) || [])[1];
    // may be a single weight ("600") or a variable range ("400 700")
    const weight = (block.match(/font-weight:\s*([\d\s]+?);/) || [])[1];
    const url = (block.match(/url\((https:\/\/[^)]+\.woff2)\)/) || [])[1];
    const unicode = (block.match(/unicode-range:\s*([^;]+);/) || [])[1];
    if (!fam || !weight || !url) continue;

    const slug = weight.trim().replace(/\s+/g, '-');
    const fname = `${fam.toLowerCase().replace(/\s+/g, '')}-${slug}-${subset.replace('-', '')}.woff2`;
    const buf = Buffer.from(await (await fetch(url, { headers: { 'User-Agent': UA } })).arrayBuffer());
    fs.writeFileSync(path.join(OUT_DIR, fname), buf);
    count++;
    bytes += buf.length;

    out +=
      `@font-face{font-family:'${fam}';font-style:normal;font-weight:${weight};` +
      `font-display:swap;src:url(fonts/${fname}) format('woff2');unicode-range:${unicode};}\n`;
    console.log(`  ${fname.padEnd(34)} ${(buf.length / 1024).toFixed(0)} KB`);
  }

  fs.writeFileSync(CSS_OUT, out);
  console.log(`\n${count} files, ${(bytes / 1024).toFixed(0)} KB total -> site/fonts/ + site/fonts.css`);
})();
